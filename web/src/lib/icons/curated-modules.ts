const PATHS = new Map(
	Object.keys(MODULES).map((path) => [path.slice('./'.length, -'.svelte'.length), path])
);

/** The names of the icons in this map. */
export const CURATED_MODULE_NAMES: readonly string[] = [...PATHS.keys()];

/** The module of a curated icon, to load; undefined for any other name. */
export function curatedModule(name: string): (() => Promise<{ default: Component }>) | undefined {
	const path = PATHS.get(name);
	return path ? MODULES[path] : undefined;
}
